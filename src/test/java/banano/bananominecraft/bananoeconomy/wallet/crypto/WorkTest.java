package banano.bananominecraft.bananoeconomy.wallet.crypto;

import org.junit.jupiter.api.Test;

import java.util.Random;

import static org.junit.jupiter.api.Assertions.*;

class WorkTest
{
    /** root, work, value: from the jNano 2.20.1 differential run (2000 random pairs, 0 mismatches). */
    private static final String[][] VALUE_VECTORS = {
            {"42C5F9253C17F7AAE3FD72FA4A207E272F3ED7B426D70A07401218DC2729637B", "13756f6d256e9765", "1449150ff12c3659"},
            {"EC482290AE1B7F36C2E00FDD0A02F57DF57F57C275EB9D8818BF04C2F06F5453", "f77ed09cca3a1921", "446e17325e352c2f"},
            {"A4609B9F11849536162A76ECD3AF6B064A676C3115A87F8B8C54C0A0E225C54F", "e33f253ecb783e2b", "9fa15cb4f18ac827"},
            {"69A0C11DCB1451A5EF2746711C9C42E6D4C581F265FC9E58210DDFDE9D235C60", "242db87949fc8558", "c381140e61480ae4"},
    };

    /** root, work: generated by CpuWorkGenerator at the Banano threshold and accepted by jNano. */
    private static final String[][] BANANO_WORK = {
            {"223BD8A29BE2B71682DCE04DAE1E266F6B6699A7194F46EF4973E26F4E79EBB5", "434668befa699040"},
            {"4704107AD4F26437BF263C74D74EBF687E4A1F86B65A790AC44706D14D2249E5", "4ff0131acd2d264c"},
            {"1DB2326716D6A15D8A7D356D5B5008F69A3D8C6905AC3D4257F2F255CF36C77D", "cb6ec7a19c8af992"},
            {"3A7DAEF6E7D132138808C44F47DFD449B7F5375D45F7BF82D8DB092F2C212271", "055b5ea5097a14ec"},
    };

    @Test
    void value_knownVectors()
    {
        for (String[] v : VALUE_VECTORS)
        {
            byte[] root = Hex.decode(v[0]);
            long work = Long.parseUnsignedLong(v[1], 16);
            long expected = Long.parseUnsignedLong(v[2], 16);
            assertEquals(expected, Work.value(root, work));
            assertEquals(expected, new WorkHasher(root).value(work));
        }
    }

    @Test
    void isValid_bananoThreshold_knownWork()
    {
        for (String[] v : BANANO_WORK)
        {
            byte[] root = Hex.decode(v[0]);
            long work = Long.parseUnsignedLong(v[1], 16);
            assertTrue(Work.isValid(root, work, Work.BANANO_THRESHOLD));
            // A different root makes the same nonce (almost certainly) invalid
            byte[] other = root.clone();
            other[0] ^= 1;
            assertFalse(Work.isValid(other, work, Work.BANANO_THRESHOLD));
        }
    }

    @Test
    void isValid_comparesUnsigned()
    {
        byte[] root = Hex.decode(VALUE_VECTORS[2][0]);
        long work = Long.parseUnsignedLong(VALUE_VECTORS[2][1], 16);
        long value = Work.value(root, work); // 0x9fa1..., negative as a signed long
        assertTrue(value < 0);
        assertTrue(Work.isValid(root, work, value));
        assertTrue(Work.isValid(root, work, 0x7fffffffffffffffL));
        assertFalse(Work.isValid(root, work, value + 1));
        assertTrue(Work.isValid(root, work, 0));
    }

    @Test
    void fastHasher_matchesReference_random()
    {
        Random rnd = new Random(3);
        for (int i = 0; i < 20000; i++)
        {
            byte[] root = new byte[32];
            rnd.nextBytes(root);
            long work = rnd.nextLong();
            assertEquals(Work.value(root, work), new WorkHasher(root).value(work));
        }
    }

    @Test
    void value_isBlake2b8OfLittleEndianNonceAndRoot()
    {
        byte[] root = Hex.decode(VALUE_VECTORS[0][0]);
        long work = 0x0102030405060708L;
        byte[] le = {8, 7, 6, 5, 4, 3, 2, 1};
        byte[] h = Blake2b.digest(8, le, root);
        long expected = 0;
        for (int i = 7; i >= 0; i--)
        {
            expected = (expected << 8) | (h[i] & 0xff);
        }
        assertEquals(expected, Work.value(root, work));
    }

    @Test
    void invalidRoot_throws()
    {
        assertThrows(IllegalArgumentException.class, () -> Work.value(new byte[31], 0));
        assertThrows(IllegalArgumentException.class, () -> new WorkHasher(null));
    }
}
